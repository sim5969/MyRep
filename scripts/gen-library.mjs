/**
 * Блок управления электродвигателем с прямым пуском (панель 04).
 * Ширина блока bw, левый край x.
 */
function motorBlock(b, x, bw, k, y0) {
  const cx = x + bw / 2
  const w = bw - 8
  const lx = cx - w / 2
  b.cell({ id: `T${k}`, x: lx, y: y0, w, h: LABEL_H, text: ['Нагрузка, %', `Насос Н-${k}`] })
  b.ind(cx - IND_W / 2, y0 + LABEL_H + 2)
  b.strip(lx, y0 + 80, w, [
    { id: `A${k}1`, text: ['Готов'] },
    { id: `A${k}2`, text: ['Включен'] },
    { id: `A${k}3`, text: ['Автомат'] },
    { id: `A${k}4`, text: ['Стоп PLC'] },
  ])
  const lampColors = ['green', 'white', 'green', 'red']
  for (let i = 0; i < 4; i++) b.lamp(lx + (w / 8) * (2 * i + 1), y0 + 106, lampColors[i])
  b.strip(lx, y0 + 124, w, [
    { id: `S${k}1`, text: ['Стоп'] },
    { id: `S${k}2`, text: ['Разр.'] },
    { id: `S${k}3`, text: ['Пуск'] },
    { id: `S${k}4`, text: ['Ручное'], span: 1.5 },
    { id: `S${k}5`, text: ['Автомат'], span: 1.5 },
  ])
  b.sw(lx + w * 0.25, y0 + 154)
  b.sw(lx + w * 0.75, y0 + 154)
}

