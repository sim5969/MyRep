/** Тип сигнала канала на стороне ПЛК */
export type SignalType =
  | 'AI' // аналоговый вход (ток, напряжение)
  | 'AO' // аналоговый выход
  | 'DI' // дискретный вход
  | 'DO' // дискретный выход
  | 'RTD' // термосопротивление (PT100, PT1000, ТСМ)
  | 'TC' // термопара
  | 'RS485' // последовательный интерфейс
  | 'Ethernet'

/** Взрывозащита цепи */
export type ExType =
  | 'Exi' // искробезопасная цепь, через барьер или разделитель
  | 'Exd' // цепь без искрозащиты (взрывонепроницаемая оболочка датчика)
  | 'нет'

/** Что подключается к каналу. Список закрытый: по нему собираются выгрузки */
export type DeviceKind =
  | 'ПЧ' // станция управления с преобразователем частоты
  | 'ЭКМ' // электроконтактный манометр
  | 'датчик' // датчик с аналоговым или дискретным выходом
  | 'прибор' // прибор со своим индикатором или интерфейсом
  | 'задвижка' // электропривод запорной или регулирующей арматуры
  | 'двигатель' // двигатель с прямым пуском

/**
 * Канал подключения — точка, к которой снаружи подключается одно устройство:
 * станция с ПЧ, манометр, датчик, прибор. Это не сигнал ПЛК: сигналы внутри
 * канала не расписываются построчно, а считаются сводкой в `signals`.
 *
 * Часть каналов на лицевую панель не выводится (`facade: false`) — манометры,
 * термосопротивления подшипников, датчики вибрации. Они не дают ни приборов,
 * ни шильдов, но занимают входы ПЛК и место в кабельном журнале.
 *
 * Каналы разных исполнений одной панели (Exi с барьерами и Exd без них)
 * описываются отдельными записями библиотеки со своими кодами: код участвует
 * в обозначении секции, а комплект барьеров — это другое железо и другая цена.
 *
 * Данные лежат в docs/каналы/<код>.md, разбор — scripts/channels.mjs.
 * Подробнее — docs/Каналы подключения.md.
 */
export interface ChannelSpec {
  /** Обозначение канала в модуле: «ПЧ1», «ЭКМ1», «AI3» */
  id: string
  kind: DeviceKind
  /** Что именно подключается: «ПЧ ABB», «ЭКМ-1У», «Метран-55» */
  device?: string
  /**
   * Номер объекта модуля (с единицы) — тот же, которым оперирует подбор
   * модулей (`scripts/kinds.mjs`, поле `cap`). Через него канал связан с
   * блоком фасада и его шильдами. Несколько каналов могут ссылаться на один
   * объект: у станции с ПЧ это органы управления и манометр.
   */
  object?: number
  /** Выводится ли канал на лицевую панель. `false` — приборов и шильдов нет */
  facade?: boolean
  /** Сводка сигналов ПЛК: `{ AI: 2, DI: 4, DO: 4 }`. Пусто — данных нет */
  signals?: Partial<Record<SignalType, number>>
  ex?: ExType
  /** Барьер искрозащиты или разделитель в цепи. Идёт в спецификацию секции */
  barrier?: { article?: string; name: string; qty?: number }
  /** Клеммы по рабочей документации: «1XT1», «XT5:1,2» */
  terminal?: string
  /** Модули или входы ПЛК, которые занимает канал: «AI1, DI1, DO1» */
  plc?: string
  /** Назначение канала, если оно закреплено исполнением панели */
  purpose?: string
}

export interface ModuleSpec {
  /** Двузначный код, участвует в обозначении секции. S1 — панель слота 1 */
  code: string
  name: string
  /** Артикул лицевой панели по рабочей документации, например «НТ53-45.02» */
  article?: string
  slotHeight: 250 | 400
  allowedSlots: number[]
  price: number | null
  devices: DeviceSpec[]
  labels: LabelSpec[]
  /**
   * Каналы подключения датчиков, в том числе не выводимые на фасад.
   * Пока заполнены не у всех панелей: данные берутся из рабочей документации.
   * Источник — docs/каналы/<код>.md, разбор — scripts/channels.mjs.
   */
  channels?: ChannelSpec[]
}

// ---------------------------------------------------------------------------
// Проект
// ---------------------------------------------------------------------------

export interface SlotInstance {
  n: number
  moduleCode: string
  /** Значения редактируемых надписей: id поля → строки */
  labels: Record<string, string[]>
}

export interface Section {
  /** Внутренний идентификатор (не отображается) */
  uid: string
  slots: SlotInstance[]
}

/**
 * Комплекс секций управления (КСУ) — набор секций, стоящих в один ряд.
 * Секции внутри комплекса обозначаются по порядку: SEC1, SEC2 и так далее.
 */
export interface Complex {
  id: string
  sections: Section[]
}

export interface ProjectMeta {
  name: string
  code: string
  author: string
  date: string
  /**
   * Графы основной надписи фирменной рамки ООО «НТ»:
   * обозначение документа, наименование объекта берётся из name,
   * наименование здания, стадия, организация и фамилии подписей.
   */
  docCode?: string
  building?: string
  stage?: string
  org?: string
  checker?: string
  inspector?: string
  gip?: string
}

export interface Project {
  /** 1 — секции назывались шкафами, комплекс — секцией */
  version: 1 | 2
  project: ProjectMeta
  complexes: Complex[]
}

/** Файл, из которого открыт или в который сохранён проект. В сам JSON не входит */
export interface ProjectFile {
  name: string
  /**
   * Дескриптор File System Access API — по нему диалог сохранения открывается в той же папке.
   * null — файл пришёл через `<input type="file">` или проект ещё не сохранялся.
   */
  handle: FileSystemFileHandle | null
}
