/** Типы данных конфигуратора. Все размеры — в миллиметрах. */

export type DeviceType =
  | 'indicator' // цифровой индикатор (ТРМ и аналоги)
  | 'lamp' // лампа сигнальная Ø22
  | 'switch' // переключатель поворотный Ø22
  | 'opPanel' // панель оператора / сенсорная панель
  | 'meter' // щитовой стрелочный прибор
  | 'device' // прочий прибор

export type LampColor = 'green' | 'red' | 'blue' | 'yellow' | 'white'

/**
 * Шильд на лицевой панели: прямоугольная ячейка с рамкой и текстом.
 * Соседние ячейки с общей границей образуют полосу надписей.
 */
export interface LabelSpec {
  /** Ключ поля в экземпляре модуля */
  id: string
  x: number
  y: number
  w: number
  /** Высота ячейки шильда */
  h: number
  /** Количество строк */
  lines: number
  /** Ограничение длины по строкам */
  maxChars: number[]
  /** Текст по умолчанию */
  default: string[]
  /** Разрешено ли редактирование пользователем */
  editable: boolean
  /** Рисовать рамку шильда */
  box?: boolean
  align?: 'center' | 'left'
  fontSize?: number
}

export interface DeviceSpec {
  /** Номер устройства в модуле, участвует в позиционном обозначении «слот.номер» */
  id: string
  type: DeviceType
  x: number
  y: number
  w: number
  h: number
  color?: LampColor
  /** Неизменяемая подпись под устройством (например «Ручн/Откл/Авт») */
  caption?: string
  /** Наименование прибора для спецификации */
  name?: string
  /** Артикул производителя (из рабочей документации) */
  article?: string
  /** Позиционное обозначение прибора по РД, например «1HG1» */
  ref?: string
  /**
   * Прибор встроен в другой прибор: id прибора-носителя. Так описывается
   * подсветка переключателя — она входит в состав, но своего отверстия в панели
   * не имеет и на чертёж фасада отдельным контуром не выводится.
   */
  builtIn?: string
  /** Монтажный вырез в панели: прямоугольный (w × h) или круглый (d) */
  cutout?: { w?: number; h?: number; d?: number }
  /** Для приборов типа device: количество полей индикации */
  displays?: number
  /** Цвет полей индикации */
  displayColor?: string
}

